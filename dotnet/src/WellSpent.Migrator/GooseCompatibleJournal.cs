using System.Data;
using DbUp.Engine;
using Npgsql;

namespace WellSpent.Migrator;

/// <summary>A DbUp journal backed by goose's own `goose_db_version` table, so this runner and Go's `cmd/migrate` can safely interleave against the same database.</summary>
public sealed class GooseCompatibleJournal(string connectionString, IReadOnlyList<SqlScript> scripts, Action<string> log) : IJournal
{
    private const string TableName = "goose_db_version";

    public string[] GetExecutedScripts()
    {
        using var connection = new NpgsqlConnection(connectionString);
        connection.Open();
        if (!TableExists(connection)) return [];

        using var command = connection.CreateCommand();
        command.CommandText = $"SELECT DISTINCT version_id FROM {TableName} WHERE is_applied = true";
        var appliedVersions = new HashSet<long>();
        using var reader = command.ExecuteReader();
        while (reader.Read())
        {
            appliedVersions.Add(reader.GetInt64(0));
        }

        return scripts.Where(s => TryParseGooseVersion(s.Name, out var v) && appliedVersions.Contains(v)).Select(s => s.Name).ToArray();
    }

    public void EnsureTableExistsAndIsLatestVersion(Func<IDbCommand> dbCommandFactory)
    {
        using (var create = dbCommandFactory())
        {
            // Exact schema goose v3's Postgres dialect creates, so a database migrated first by goose and a database migrated first by this runner end up identical.
            create.CommandText = $"""
                CREATE TABLE IF NOT EXISTS {TableName} (
                    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                    version_id bigint NOT NULL,
                    is_applied boolean NOT NULL,
                    tstamp timestamp NOT NULL DEFAULT now()
                )
                """;
            create.ExecuteNonQuery();
        }

        using var count = dbCommandFactory();
        count.CommandText = $"SELECT COUNT(*) FROM {TableName}";
        if (Convert.ToInt64(count.ExecuteScalar()) > 0) return;

        // Bootstrap row, matching goose's own EnsureDBVersion behavior on a fresh table.
        using var insert = dbCommandFactory();
        insert.CommandText = $"INSERT INTO {TableName} (version_id, is_applied) VALUES (0, true)";
        insert.ExecuteNonQuery();
    }

    public void StoreExecutedScript(SqlScript script, Func<IDbCommand> dbCommandFactory)
    {
        if (!TryParseGooseVersion(script.Name, out var version))
        {
            // Doesn't follow goose's NNNNNN_name.sql convention — nothing to record in a goose-shaped table.
            log($"warn: {script.Name} has no goose-style version prefix, not recorded in {TableName}");
            return;
        }

        using var command = dbCommandFactory();
        command.CommandText = $"INSERT INTO {TableName} (version_id, is_applied) VALUES (@version, true)";
        var param = command.CreateParameter();
        param.ParameterName = "version";
        param.Value = version;
        command.Parameters.Add(param);
        command.ExecuteNonQuery();
    }

    /// <summary>Mirrors goose's NumericComponent: the digits before the first underscore.</summary>
    private static bool TryParseGooseVersion(string scriptName, out long version)
    {
        version = 0;
        var underscoreIndex = scriptName.IndexOf('_');
        return underscoreIndex > 0 && long.TryParse(scriptName[..underscoreIndex], out version);
    }

    private static bool TableExists(NpgsqlConnection connection)
    {
        using var command = connection.CreateCommand();
        command.CommandText = "SELECT EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = current_schema() AND tablename = @table)";
        var param = command.CreateParameter();
        param.ParameterName = "table";
        param.Value = TableName;
        command.Parameters.Add(param);
        return (bool)command.ExecuteScalar()!;
    }
}
